	// Multiply by x in GF(2^8), which is every product MixColumns needs.
	static uint8_t Xtime(uint8_t value)
	{
		return static_cast<uint8_t>((value << 1) ^ ((value >> 7) * 0x1B));
	}

	// The key schedule, expanded once so a caller encrypting five hundred blocks pays for it once.
	Aes128::Aes128(const uint8_t key[AesBlockSize])
	{
		std::memcpy(Round[0], key, AesBlockSize);
		uint8_t rcon = 1;

		for (int r = 1; r <= 10; r++)
		{
			const uint8_t* previous = Round[r - 1];
			uint8_t* out = Round[r];

			// RotWord and SubWord folded together on the last column of the previous key.
			out[0] = previous[0] ^ Sbox[previous[13]] ^ rcon;
			out[1] = previous[1] ^ Sbox[previous[14]];
			out[2] = previous[2] ^ Sbox[previous[15]];
			out[3] = previous[3] ^ Sbox[previous[12]];

			for (int i = 4; i < static_cast<int>(AesBlockSize); i++)
				out[i] = out[i - 4] ^ previous[i];

			rcon = Xtime(rcon);
		}
	}

	// The state is held column major, so byte i is row i % 4 of column i / 4.
	void Aes128::EncryptBlock(uint8_t block[AesBlockSize]) const
	{
		for (size_t i = 0; i < AesBlockSize; i++)
			block[i] ^= Round[0][i];

		for (int r = 1; r <= 10; r++)
		{
			for (size_t i = 0; i < AesBlockSize; i++)
				block[i] = Sbox[block[i]];

			uint8_t t = block[1];
			block[1] = block[5];
			block[5] = block[9];
			block[9] = block[13];
			block[13] = t;

			t = block[2];
			block[2] = block[10];
			block[10] = t;
			t = block[6];
			block[6] = block[14];
			block[14] = t;

			t = block[15];
			block[15] = block[11];
			block[11] = block[7];
			block[7] = block[3];
			block[3] = t;

			// The last round has no MixColumns.
			if (r != 10)
			{
				for (size_t c = 0; c < AesBlockSize; c += 4)
				{
					const uint8_t a0 = block[c], a1 = block[c + 1], a2 = block[c + 2], a3 = block[c + 3];
					const uint8_t all = a0 ^ a1 ^ a2 ^ a3;

					block[c + 0] ^= all ^ Xtime(a0 ^ a1);
					block[c + 1] ^= all ^ Xtime(a1 ^ a2);
					block[c + 2] ^= all ^ Xtime(a2 ^ a3);
					block[c + 3] ^= all ^ Xtime(a3 ^ a0);
				}
			}

			for (size_t i = 0; i < AesBlockSize; i++)
				block[i] ^= Round[r][i];
		}
	}

	// Refuses a length that is not whole blocks rather than padding: the far end reads a fixed size
	// and a short final block would decrypt to rubbish it cannot tell from data.
	bool Aes128::EncryptCbc(const uint8_t* in, uint8_t* out, size_t length, const uint8_t iv[AesBlockSize]) const
	{
		if (!in || !out || !iv || length % AesBlockSize)
			return false;

		uint8_t chain[AesBlockSize] = {};
		std::memcpy(chain, iv, AesBlockSize);

		for (size_t offset = 0; offset < length; offset += AesBlockSize)
		{
			for (size_t i = 0; i < AesBlockSize; i++)
				chain[i] ^= in[offset + i];

			EncryptBlock(chain);
			std::memcpy(out + offset, chain, AesBlockSize);
		}
		return true;
	}
